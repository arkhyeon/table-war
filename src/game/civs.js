export const RANDOM_CIVS = Object.keys(CIVS).filter((k) => k !== 'tk' && k !== 'rome');

export function makeNamer(rng) {
  const used = new Set();
  return (civ) => {
    const c = CIVS[civ] || CIVS.china;
    for (let i = 0; i < 40; i++) {
      const n = rng.pick(c.pre) + rng.pick(c.suf);
      if (!used.has(n)) {
        used.add(n);
        return n;
      }
    }
    let k = 2;
    const base = rng.pick(c.pre) + rng.pick(c.suf);
    while (used.has(base + k)) k++;
    used.add(base + k);
    return base + k;
  };
}
