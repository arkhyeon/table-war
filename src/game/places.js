// 거의 같은 자리(약 25km 안)에 이름이 둘 이상이면 먼저 나온(대표) 이름 하나만 — 시대마다 다른 이름이 번갈아 나오지 않게
{
  const keep = [];
  for (const p of PLACES) {
    if (p.area) { keep.push(p); continue; }
    const q = keep.find((k) => !k.area && Math.abs(k.lon - p.lon) < 0.25 && Math.abs(k.lat - p.lat) < 0.25);
    if (!q) { keep.push(p); continue; }
    // 대표 이름이 있던 기간을 넓혀 둘을 합침
    q.from = q.from == null || p.from == null ? null : Math.min(q.from, p.from);
    q.until = q.until == null || p.until == null ? null : Math.max(q.until, p.until);
  }
  PLACES.length = 0;
  PLACES.push(...keep);
}

// 그 해에 있던 곳인지 (건설 전·소멸 후 제외)
export const placeExists = (p, year) => (p.from == null || year >= p.from) && (p.until == null || year < p.until);

// 그 시대의 이름
export function placeName(p) {
  return p.name; // 시대와 상관없이 같은 이름
}

// 지역마다 실제 지명 붙이기: ① 그 지명이 들어 있는 지역 ② 남은 지역은 가까운 미사용 지명
// ③ 그래도 남으면 '가까운 지명 + 방위'(예: 평양 북부). reserved = 이미 쓰는 이름(수도 등)
const DIRS = ['동부', '남동부', '남부', '남서부', '서부', '북서부', '북부', '북동부'];
export function assignRealNames(world, year, reserved = new Set()) {
  const land = world.regions.filter((r) => !r.sea);
  const out = {};
  const used = new Set(reserved);
  const pts = PLACES.filter((p) => placeExists(p, year)).map((p) => {
    const [x, y] = world.toPx(p.lon, p.lat);
    return { name: placeName(p, year), x, y };
  }).filter((p) => p.x >= 0 && p.y >= 0 && p.x <= world.W && p.y <= world.H);
  for (const p of pts) {
    const r = world.regionAt(p.x, p.y);
    if (r < 0 || out[r] || used.has(p.name)) continue;
    out[r] = p.name;
    used.add(p.name);
  }
  // ② 가까운 미사용 지명 (지역 크기의 2배 거리까지)
  const span = Math.sqrt((world.W * world.H) / Math.max(1, land.length));
  const pairs = [];
  for (const r of land) {
    if (out[r.id]) continue;
    for (const p of pts) {
      if (used.has(p.name)) continue;
      const d = Math.hypot(p.x - r.cx, p.y - r.cy);
      if (d < span * 2) pairs.push([d, r.id, p.name]);
    }
  }
  pairs.sort((a, b) => a[0] - b[0]);
  for (const [, rid, nm] of pairs) {
    if (out[rid] || used.has(nm)) continue;
    out[rid] = nm;
    used.add(nm);
  }
  // ③ 가까운 지명 + 방위
  for (const r of land) {
    if (out[r.id]) continue;
    const near = pts.map((p) => [Math.hypot(p.x - r.cx, p.y - r.cy), p]).sort((a, b) => a[0] - b[0]).slice(0, 6);
    let nm = null;
    for (const [, p] of near) {
      const ang = Math.atan2(-(r.cy - p.y), r.cx - p.x);
      const k = ((Math.round(ang / (Math.PI / 4)) % 8) + 8) % 8;
      for (const dk of [0, 1, -1, 2, -2]) {
        const cand = `${p.name} ${DIRS[(((k + dk) % 8) + 8) % 8]}`;
        if (!used.has(cand)) { nm = cand; break; }
      }
      if (nm) break;
    }
    if (nm) {
      out[r.id] = nm;
      used.add(nm);
    }
  }
  return out;
}
