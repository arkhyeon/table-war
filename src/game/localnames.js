export function localName(civ, rng, taken, fallback) {
  const key = P[civ] ? civ : P[ALIAS[civ]] ? ALIAS[civ] : P[fallback] ? fallback : 'china';
  const [a, b, sep] = P[key];
  for (let i = 0; i < 40; i++) {
    const n = rng.pick(a) + sep + rng.pick(b);
    if (!taken.has(n.trim())) return n.trim();
  }
  return `${rng.pick(a)}${sep}${rng.pick(b)} ${rng.int(2, 9)}세`;
}
