export const tval = (id, tier) => T14[id]?.val[Math.max(1, Math.min(3, tier)) - 1] ?? 0;
export const tdesc = (id, tier) => (T14[id] ? T14[id].desc(tval(id, tier)) : '');
export const tlabel = ([id, tier]) => `${id}${['', 'Ⅰ', 'Ⅱ', 'Ⅲ'][tier] || ''}`;
// 장수 무리에서 그 특성의 가장 높은 값 (없으면 0)
export function t14(gens, id) {
  let bt = 0;
  for (const g of gens) for (const [t, tier] of g?.traits || []) if (t === id && tier > bt) bt = tier;
  return bt ? tval(id, bt) : 0;
}
