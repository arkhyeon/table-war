export const HIST_TRAITS = {};
for (const line of RAW.trim().split('\n')) {
  const parts = line.trim().split(/\s+/);
  const tr = [];
  while (parts.length && /\d$/.test(parts[parts.length - 1])) tr.unshift(parts.pop());
  const name = parts.join(' ');
  HIST_TRAITS[name] = tr.map((t) => { const k = t.slice(0, -1), tier = +t.slice(-1); return [T14[k] ? k : MAP14[k], tier]; }).filter(([k]) => k && T14[k]).slice(0, 3);
}
export const histTraitsOf = (name) => (HIST_TRAITS[name]?.length ? HIST_TRAITS[name].map(([k, t]) => [k, t]) : null);

// 「역사 능력치 사용」을 껐을 때: 특성 1~3개 무작위 (등급도 무작위, 능력치와 따로)
const ALL = Object.keys(T14);
export function randomTraits(rng) {
  const r = rng(), n = r < 0.45 ? 1 : r < 0.8 ? 2 : 3;
  const out = [];
  while (out.length < n) {
    const k = ALL[Math.floor(rng() * ALL.length)];
    if (out.some(([x]) => x === k)) continue;
    const q = rng();
    out.push([k, q < 0.5 ? 1 : q < 0.85 ? 2 : 3]);
  }
  return out;
}
